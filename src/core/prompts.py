"""
ساخت پرامپت‌ها (فارسی)
======================
- پرامپت سیستمی: معرفی نقش، سیاست «تصمیم با مدل» برای استفاده از ابزار،
  و آموزش قالب فراخوانی ابزار (hermes سازگار با Qwen3)
- پیام کاربر: همان متن خامِ کاربر (هیچ بافتِ خودکاری تزریق نمی‌شود)
- قالب پاسخ ابزار به مدل (همان چیزی که مدل پس از فراخوانی می‌بیند)
"""

from __future__ import annotations

import json

from .tools import TOOL_DEFINITIONS

TOOL_CALL_OPEN = "<tool_call>"
TOOL_CALL_CLOSE = "</tool_call>"


def render_tool_instructions() -> str:
    """معرفی ابزارها به مدل به سبک hermes (سازگار با Qwen3).

    نکتهٔ مهم: تجربه نشان داده مدل گاهی فراخوانی را «بدون تگ» و به‌صورت
    JSON خالی می‌نویسد؛ سمت پارسر هر دو حالت پشتیبانی می‌شود، اما اینجا
    قالبِ تگ‌دار با تأکید کامل آموزش داده می‌شود تا مطمئن‌ترین مسیر باشد.
    """
    lines: list[str] = [
        "# ابزارها (Tools)",
        "",
        "می‌توانی برای کسب اطلاعات بیشتر از ابزارهای زیر استفاده کنی.",
        "",
        "## قالب فراخوانی (خیلی مهم — دقیقاً همین ساختار)",
        f"فراخوانی ابزار را همیشه داخل تگ‌های {TOOL_CALL_OPEN} و {TOOL_CALL_CLOSE} بنویس:",
        "",
        TOOL_CALL_OPEN,
        '{"name": "نام_ابزار", "arguments": {"پارامتر": "مقدار"}}',
        TOOL_CALL_CLOSE,
        "",
        "قواعد رعایت قالب:",
        f"- تگ {TOOL_CALL_OPEN} و {TOOL_CALL_CLOSE} بخشی از دستور هستند و حذف‌شان نکن.",
        "- داخل تگ فقط همان یک شیء JSON را بنویس؛ متن اضافه داخل تگ نگذار.",
        "- بلافاصله بعد از بستن تگ، نوشتن را متوقف کن و منتظر نتیجه بمان؛",
        "  نتیجهٔ ابزار در پیام بعدی به تو داده می‌شود.",
        "- هرگز نتیجهٔ ابزار را از خودت نساز و JSON فراخوانی را در پاسخ نهایی تکرار نکن.",
        "",
        "ابزارهای موجود:",
        "",
    ]
    for tool in TOOL_DEFINITIONS:
        function = tool["function"]
        params = function.get("parameters", {}).get("properties", {})
        param_names = ", ".join(params) if params else "بدون پارامتر"
        lines.append(f"- {function['name']}({param_names}): {function['description']}")
    lines += [
        "",
        "قواعد استفاده از ابزار:",
        "- فقط وقتی ابزار را صدا بزن که واقعاً به اطلاعات دانش‌نامه نیاز داری.",
        "- در هر نوبت حداکثر یک فراخوانی؛ سپس منتظر نتیجه بمان.",
        "- هرگز خروجی ساختگی برای ابزار نساز؛ نتیجه در پیام بعدی به تو داده می‌شود.",
    ]
    return "\n".join(lines)


